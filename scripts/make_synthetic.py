def money(x: float) -> str:
    return f"{x:,.2f}"


def lines(r, pool, lo=2, hi=6):
    return [(d, r.randint(1, 10), round(p * r.uniform(0.8, 1.3), 2)) for d, p in r.sample(pool, r.randint(lo, hi))]


def totals(rows, rate):
    sub = round(sum(q * p for _, q, p in rows), 2)
    tax = round(sub * rate, 2)
    return sub, tax, round(sub + tax, 2)


def when(f):
    return f.date_between(start_date="-2y", end_date="today")


# ------------------------------------------------------------------ invoices
def inv_1(f, r):
    sym, rows, d, days = r.choice("€$£"), lines(r, SERVICES + GOODS), when(f), r.choice([14, 30, 45])
    sub, tax, tot = totals(rows, 0.2)
    out = ["INVOICE", "", f"Invoice No: {r.randint(1000, 99999)}", f"Issue date: {d:%d %B %Y}",
           f"Due date: {d + timedelta(days=days):%d %B %Y}", "", f.company(), f.address(), "",
           "Bill to:", f.company(), f.address(), "", "Description | Qty | Unit price | Amount"]
    out += [f"{n} | {q} | {sym}{money(p)} | {sym}{money(q * p)}" for n, q, p in rows]
    out += ["", f"Subtotal: {sym}{money(sub)}", f"VAT (20%): {sym}{money(tax)}", f"TOTAL DUE: {sym}{money(tot)}", "",
            f"Payment terms: net {days} days", f"Bank transfer to IBAN {f.iban()}, reference {r.randint(1000, 99999)}"]
    return "\n".join(out)


