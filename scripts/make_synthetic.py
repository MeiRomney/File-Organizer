def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-n", "--per-category", type=int, default=100)
    ap.add_argument("--categories", nargs="+", default=list(GENERATORS), choices=list(GENERATORS))
    ap.add_argument("--formats", default=DEFAULT_FORMATS)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    fake = Faker("en_GB")
    Faker.seed(args.seed)
    rng = random.Random(args.seed)
    store = Store()
    for cat in args.categories:
        gens, made, i = GENERATORS[cat], 0, 0
        while made < args.per_category and i < args.per_category * 5:
            t, i = i % len(gens), i + 1          # templates used round-robin => balanced
            stem = f"{rng.choice(NAMES)}_{rng.randint(100, 9999)}"
            ok = store.save_text(cat, stem, gens[t](fake, rng), pick_format(rng, args.formats),
                                 f"synthetic:template{t + 1}", LICENCE)
            made += bool(ok)
        print(f"{cat}: generated {made} (folder now has {store.count(cat)})")


if __name__ == "__main__":
    main()